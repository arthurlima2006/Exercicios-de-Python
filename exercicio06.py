# Problema: "A soma de dois números consecutivos é 47."
#
# Seja o primeiro número = x
# O número consecutivo a ele = x + 1
#
# Equação:
# x + (x + 1) = 47
# 2x + 1 = 47
# 2x = 47 - 1
# 2x = 46
# x = 46 / 2
# x = 23

# Operações
numero = 47
x1 = 23
x2 = x1 + 1
soma = x1 + x2

# Resultados
print(f"Se o número dado no exercício é {numero}")
print(f"E o primeiro número é {x1}, logo temos que o número consecutivo à ele é {x2}, como dado no enunciado.")
print(f"Então podemos concluir que {x1} + {x2} = {soma}, resultando no número dado pela questão.")