# Problema: "Multiplique um número por 3 e subtraia 9. O resultado é igual ao próprio número."
# Equação: 3x - 9 = x

# Resolvendo a equação:
# 3x - x = 9
# 2x = 9
# x = 9 / 2
# x = 4.5

# ---------------------------------------------------------------------------------------------------

# Definição das operações
x = 4.5
multiplicacao = x * 3
subtracao = multiplicacao - 9

# Exibição dos resultados
print(f"O número dito no exercício é {x}.")
print(f"Multiplicando o mesmo por 3 temos que {x} x 3 = {multiplicacao}.")
print(f"Por fim subtraindo tudo por 9 temos que {multiplicacao} - 9 = {subtracao}.")
