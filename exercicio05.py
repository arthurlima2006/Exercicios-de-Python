# Problema: "O triplo de um número menos 5 é igual ao dobro do mesmo número mais 1."
# Equação: 3x - 5 = 2x + 1

# Resolvendo a equação:
# 3x - 2x = 1 + 5
# x = 6

# Operações
numero = 6
triplo_menos_cinco = numero * 3 - 5
dobro_mais_um = numero * 2 + 1

# Resultados
print(f"O número correspondido à questão é: {numero}.")
print(f"Seu triplo subtraido por 5 é: {triplo_menos_cinco}.")
print(f"E seu dobro somado por 1 é: {dobro_mais_um} também.")
print(f"Logo podemos concluir que o triplo de {numero} subtraido por 5 é igual ao dobro de {numero} somado por 1")